DRIFT = _table("""
    catalog-index :: docs/skills/README.md :: First sentence. :: Edited. :: block catalog-index
    releases :: ROADMAP.md :: | Unreleased | :: | v9.9.9 | :: block releases
    planned-skills :: ROADMAP.md :: Standard skills :: Several skills :: block planned-skills
    category-extras :: docs/usage/install_extras.md :: | `alpha` | `alpha/ :: | `alpha` | `x/ :: block category-extras
    skill-extras :: docs/usage/install_extras.md :: | `beta_second_skill` | :: | `beta_x` | :: block skill-extras
    categories :: CONTRIBUTING.md :: [1](docs/skills/README.md#alpha) :: 2 :: block categories
    labels :: .github/labels.json :: category — gamma :: category: gamma :: category labels
    pyproject :: pyproject.toml :: beta_second_skill = [] :: beta_second_skill = ["numpy"] :: extras block
    """)  # id :: file :: text written by --write :: hand edit :: named in the report


@pytest.mark.parametrize(("relative", "old", "new", "named"), DRIFT)
def test_check_fails_on_drift_and_names_the_block(
    sync, tmp_path, capsys, relative, old, new, named
):
    repo = _make_repo(tmp_path)
    assert _run(sync, repo, "--write") == 0
    assert _run(sync, repo, "--check") == 0
    path = repo / relative
    text = path.read_text(encoding="utf-8")
    assert old in text
    path.write_text(text.replace(old, new, 1), encoding="utf-8")
    capsys.readouterr()
    assert _run(sync, repo, "--check") == 1
    assert f"{relative}: {named}" in "".join(capsys.readouterr())


