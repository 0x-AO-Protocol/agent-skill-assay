def test_output_is_byte_identical_across_hash_seeds(tmp_path):
    snapshots = []
    for seed in ("0", "4242"):
        repo = _make_repo(tmp_path / f"seed{seed}")
        env = dict(os.environ)
        env["PYTHONHASHSEED"] = seed
        result = subprocess.run(
            [sys.executable, str(SCRIPT), "--root", str(repo), "--write"],
            cwd=ROOT,
            env=env,
            capture_output=True,
            text=True,
            check=False,
        )
        assert result.returncode == 0, result.stdout + result.stderr
        snapshots.append(_snapshot(repo))
    assert snapshots[0] == snapshots[1]


