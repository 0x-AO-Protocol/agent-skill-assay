def _text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(textwrap.dedent(content).lstrip("\n"), encoding="utf-8")


def _empty_block(name: str) -> str:
    return f"<!-- registry-sync:begin {name} -->\n<!-- registry-sync:end {name} -->\n"


def _add_bundle(
    repo: Path,
    bundle_id: str,
    *,
    title: str | None = None,
    short: str = "Do one thing well. Then stop.",
    version: str = "0.1.0",
    org: str = "AO",
    extra: dict | None = None,
) -> Path:
    category, name = bundle_id.split("/")
    bundle = repo / "skills" / category / name
    bundle.mkdir(parents=True)
    (bundle / "__init__.py").touch()
    (bundle / "skill.py").write_text("VALUE = 1\n", encoding="utf-8")
    manifest = {
        "name": bundle_id,
        "version": version,
        "short_description": short,
        "issuer": {"name": "Example", "email": "x@example.com", "org": org},
    }
    manifest.update(extra or {})
    (bundle / "manifest.yaml").write_text(
        yaml.safe_dump(manifest, sort_keys=False), encoding="utf-8"
    )
    page_title = title or name.replace("_", " ").title()
    _text(repo / "docs" / "skills" / f"{name}.md", f"# {page_title}\n\nBody.\n")
    return bundle


def _make_repo(tmp_path: Path) -> Path:
    repo = tmp_path / "repo"
    (repo / "skills").mkdir(parents=True)
    (repo / "skills" / "__init__.py").touch()
    (repo / "skills" / "beta").mkdir()
    (repo / "skills" / "beta" / "__init__.py").touch()
    _add_bundle(repo, "alpha/first_skill", short="First sentence. Second one.")
    _add_bundle(repo, "beta/second_skill", title="Second Skill", version="1.2.0")
    _text(
        repo / "CONTRIBUTING.md",
        """
        # Contributing

        ## Skill categories

        <!-- registry-sync:begin categories -->
        | Category | Purpose | Skills |
        | :--- | :--- | :--- |
        | `beta` | Beta purpose | 0 |
        | `alpha` | Alpha purpose | 0 |
        | `gamma` | Gamma purpose | 0 |
        <!-- registry-sync:end categories -->

        Text after the table.
        """,
    )
    _text(
        repo / "docs" / "skills" / "README.md",
        "# Skill Library\n\nIntro.\n\n" + _empty_block("catalog-index"),
    )
    _text(
        repo / "ROADMAP.md",
        "# Roadmap\n\n## v0.1.x releases\n\n"
        + _empty_block("releases")
        + "\n## Planned skills\n\n"
        + _empty_block("planned-skills")
        + "\n## Near-term registry work\n\n- Item.\n",
    )
    _text(
        repo / "docs" / "usage" / "install_extras.md",
        "# Install Extras\n\n## Category extras\n\n"
        + _empty_block("category-extras")
        + "\n## Skill extras\n\n"
        + _empty_block("skill-extras")
        + "\n## Meta extras\n\nHand-maintained.\n",
    )
    labels = [
        {"name": "bug", "color": "FFBCBC", "description": "Something isn't working."},
        {
            "name": "cat: stale",
            "color": "E6D9F5",
            "description": "Registry skill category — stale (`skills/stale/`).",
        },
    ]
    _text(
        repo / ".github" / "labels.json",
        json.dumps(labels, indent=4, ensure_ascii=False) + "\n",
    )
    _text(
        repo / "pyproject.toml",
        """
        [project]
        name = "example"
        version = "0.2.0"

        [project.optional-dependencies]
        dev = ["pytest"]

        # --- extras: begin generated by scripts/sync_extras.py ---
        # --- extras: end generated by scripts/sync_extras.py ---

        [tool.black]
        line-length = 88
        """,
    )
    _text(repo / "CITATION.cff", 'cff-version: 1.2.0\nversion: "0.2.0"\n')
    _text(
        repo / "CHANGELOG.md",
        """
        # Changelog

        ## [Unreleased]

        ### Added

        - `beta/second_skill`: not released yet.

        ## [0.2.0] - 2026-10-01

        ### Added

        - `alpha/first_skill`: a later Added line does not move the release.

        ### Fixed

        - `beta/second_skill`: a mention outside Added does not count.

        ## [0.1.9] - 2026-09-01

        ### Added

        - `alpha/first_skill`: first release.
        """,
    )
    return repo


def _run(sync, repo: Path, *args: str) -> int:
    return sync.main(["--root", str(repo), *args])


def _block(text: str, name: str) -> str:
    match = re.search(
        rf"<!-- registry-sync:begin {name} -->\n(.*?)<!-- registry-sync:end {name} -->",
        text,
        flags=re.DOTALL,
    )
    assert match, name
    return match.group(1)


def _read(repo: Path, relative: str) -> str:
    return (repo / relative).read_text(encoding="utf-8")


def _snapshot(repo: Path) -> dict[str, bytes]:
    return {
        path.relative_to(repo).as_posix(): path.read_bytes()
        for path in sorted(repo.rglob("*"))
        if path.is_file()
    }


