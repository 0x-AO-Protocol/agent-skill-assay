def _complete_release(repo: Path, version: str = "0.2.1") -> None:
    for relative, old, new in (
        ("pyproject.toml", 'version = "0.2.0"', f'version = "{version}"'),
        ("CITATION.cff", 'version: "0.2.0"', f'version: "{version}"'),
        (
            "CHANGELOG.md",
            "## [Unreleased]\n\n### Added\n\n- `beta/second_skill`: not released yet.\n",
            f"## [Unreleased]\n\n## [{version}] - 2026-10-08\n\n### Added\n\n"
            "- `beta/second_skill`: released.\n",
        ),
    ):
        path = repo / relative
        text = path.read_text(encoding="utf-8")
        assert old in text, relative
        path.write_text(text.replace(old, new), encoding="utf-8")


def test_release_check_passes_when_the_release_is_complete(sync, tmp_path):
    repo = _make_repo(tmp_path)
    _complete_release(repo)
    assert _run(sync, repo, "--write") == 0
    assert _run(sync, repo, "--release-check", "v0.2.1") == 0
    assert _run(sync, repo, "--release-check", "0.2.1") == 0


