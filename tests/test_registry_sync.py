def _table(text: str) -> list:
    """One case per line: "id :: value [:: value]", with \\n for a line break."""
    params = []
    for line in textwrap.dedent(text).strip("\n").splitlines():
        case_id, *values = [part.replace("\\n", "\n") for part in line.split(" :: ")]
        params.append(pytest.param(*values, id=case_id.strip()))
    return params


